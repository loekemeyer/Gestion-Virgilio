    || '-- FUNCIONES del schema GP2 — export automatico <FECHA> (pg_get_functiondef, exacto)' || E'\n'
    || '-- Fuente de verdad: Supabase (hrxfctzncixxqmpfhskv). Este archivo es respaldo/referencia.' || E'\n'
    || '-- ' || count(*) || ' funciones. Los GRANT/REVOKE no estan aca: EXECUTE para anon solo en las RPC de pantalla (ver db/README.md).' || E'\n'

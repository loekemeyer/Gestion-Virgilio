select '-- =====================================================================' || E'\n'
    || '-- VISTAS del schema GP2 (pg_get_viewdef, exacto) — export automatico <FECHA> desde Supabase (hrxfctzncixxqmpfhskv)' || E'\n'
    || '-- Respaldo/referencia. La fuente de verdad es la base; regenerar al cambiar el schema.' || E'\n'
    || '-- ' || count(*) || ' vistas. Orden de creacion: las que dependen de otra van despues.' || E'\n'
    || '-- =====================================================================' || E'\n\n'
    || string_agg('-- ---------- ' || c.relname || ' ----------' || E'\n'
                  || 'create or replace view "GP2".' || c.relname || ' as' || E'\n' || pg_get_viewdef(c.oid, true)
                  || coalesce(E'\n' || 'comment on view "GP2".' || c.relname || ' is ' || quote_literal(d.description) || ';', '') || E'\n',
                  E'\n' order by c.relname) as archivo
from pg_class c left join pg_description d on d.objoid = c.oid and d.objsubid = 0
where c.relnamespace = '"GP2"'::regnamespace and c.relkind = 'v';

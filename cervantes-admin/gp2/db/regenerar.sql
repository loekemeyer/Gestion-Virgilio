-- devuelve UN texto que se guarda tal cual como archivo. Verificar funciones con
--   select proname, md5(pg_get_functiondef(oid)) from pg_proc where pronamespace = '"GP2"'::regnamespace
-- contra el md5 de cada bloque del archivo (bloque = pg_get_functiondef + ';' + salto de linea).
